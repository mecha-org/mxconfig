//! Generate typed Rust and Dart clients from a schema.

mod dart;
mod rust;

pub use dart::dart;
pub use rust::rust;

use std::collections::BTreeMap;

use heck::{ToSnakeCase, ToUpperCamelCase};
use mxconfig_schema::{AssetSchema, KeySchema, Schema, Value};

/// Generate both clients, as `(file_name, contents)` pairs.
pub fn all(schema: &Schema) -> Result<Vec<(String, String)>, String> {
    Ok(vec![rust_file(schema)?, dart_file(schema)?])
}

/// Generate the Rust client, as a `(file_name, contents)` pair.
pub fn rust_file(schema: &Schema) -> Result<(String, String), String> {
    let stem = type_name(schema.namespace());
    Ok((format!("{stem}.rs"), rust(schema)?))
}

/// Generate the Dart client, as a `(file_name, contents)` pair.
pub fn dart_file(schema: &Schema) -> Result<(String, String), String> {
    let stem = type_name(schema.namespace()).to_snake_case();
    Ok((format!("{stem}.dart"), dart(schema)?))
}

/// The namespace's last label in `PascalCase`: `org.mechanix.demo` -> `Demo`.
pub(crate) fn type_name(namespace: &str) -> String {
    pascal(namespace.rsplit('.').next().unwrap_or(namespace))
}

/// `name` as a type name. `Self` is the only keyword in `PascalCase`.
pub(crate) fn pascal(name: &str) -> String {
    ident(name.to_upper_camel_case(), &["Self"])
}

/// The type name for a key's path: `colors.mode` -> `ColorsMode`.
pub(crate) fn path_type(key: &KeySchema) -> String {
    pascal(&format!("{} {}", key.group, key.id))
}

/// The type name for an asset: `layout` -> `AssetLayout`.
pub(crate) fn asset_type(asset: &AssetSchema) -> String {
    pascal(&format!("asset {}", asset.id))
}

/// `f` as a literal, or one of the `[nan, infinity, negative]` names.
pub(crate) fn float(f: f64, [nan, infinity, negative]: [&str; 3]) -> String {
    if f.is_nan() {
        nan.into()
    } else if f.is_infinite() {
        if f > 0.0 { infinity } else { negative }.into()
    } else {
        format!("{f:?}")
    }
}

/// `name` as a valid identifier that is not a keyword.
pub(crate) fn ident(name: String, keywords: &[&str]) -> String {
    let name = match name.chars().next() {
        None => "_".to_string(),
        Some(c) if c.is_ascii_digit() => format!("_{name}"),
        Some(_) => name,
    };
    if keywords.contains(&name.as_str()) {
        format!("{name}_")
    } else {
        name
    }
}

/// `text` on one line, for a doc comment or message.
pub(crate) fn doc(text: &str) -> String {
    text.replace(['\n', '\r'], " ")
}

/// What declared `name`, for messages about clashing names.
pub(crate) fn owner(what: &str, name: &str) -> String {
    format!("{what} `{}`", doc(name))
}

/// The comment that opens every generated file. Each block after it starts with a blank line.
pub(crate) fn header(schema: &Schema) -> String {
    format!(
        "// Generated by mxconfig-codegen from `{}` (schema v{}). Do not edit.\n",
        schema.namespace(),
        schema.version()
    )
}

/// A key's doc: its description, and the env var that overrides it.
pub(crate) fn key_doc(key: &KeySchema) -> String {
    let description = doc(key.description.trim());
    match &key.env {
        Some(var) => format!("{description} `${}` overrides it.", doc(var)),
        None => description,
    }
}

/// The key's default, if it has one that passes its own checks.
pub(crate) fn default(key: &KeySchema) -> Result<Option<&Value>, String> {
    let Some(default) = &key.default else {
        return Ok(None);
    };
    match key.check(default).into_iter().next() {
        Some(reason) => Err(format!("the default for `{}` {reason}", doc(&key.path))),
        None => Ok(Some(default)),
    }
}

/// The names used in one scope of generated code, to catch clashes.
pub(crate) struct Scope {
    what: String,
    taken: BTreeMap<String, String>,
}

impl Scope {
    /// A scope named `what`, with the `reserved` names already taken.
    pub(crate) fn new(what: impl Into<String>, reserved: &[&str]) -> Scope {
        let taken = reserved
            .iter()
            .map(|name| (name.to_string(), "the generated API".into()));
        Scope {
            what: what.into(),
            taken: taken.collect(),
        }
    }

    /// Claim `name` for `owner`. Fails if it is already taken.
    pub(crate) fn claim(&mut self, name: String, owner: &str) -> Result<String, String> {
        if let Some(other) = self.taken.get(&name) {
            return Err(format!(
                "{owner} and {other} both become `{name}` in {}",
                self.what
            ));
        }
        self.taken.insert(name.clone(), owner.to_string());
        Ok(name)
    }
}
